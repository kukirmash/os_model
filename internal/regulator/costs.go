package regulator

// ----------------------------------------------------------------------------------------
// Costs — длительности системных действий модели в тактах (лабораторная работа 7).
//
// Системные действия выполняются не пользовательским процессом, а ОС.
// Их время не сдвигает модельные такты пользовательских команд, а
// начисляется процессам: собственные затраты — в поля PSW, готовым
// процессам — в SystemWaitTicks подпрограммой IncreaseReadyTime.
type Costs struct {
	Load        int // T_загр: загрузка задания
	Dispatch    int // T_перекл: выбор и активация процесса на ЦПр
	IOInit      int // T_иниц.ВВ: логическая инициализация ввода-вывода
	IOInterrupt int // T_прерыв: обслуживание прерывания по окончании ВВ
	Terminate   int // T_заверш: завершение и выгрузка задания
}

// ----------------------------------------------------------------------------------------
// DefaultCosts возвращает длительности системных действий по умолчанию.
// Значения подобраны так, чтобы системные затраты были заметны на фоне
// 10–20 команд задания, но не замедляли демонстрационную модель чрезмерно.
func DefaultCosts() Costs {
	return Costs{
		Load:        2,
		Dispatch:    1,
		IOInit:      1,
		IOInterrupt: 1,
		Terminate:   1,
	}
}
