package regulator

import "os_model/internal/process"

// ----------------------------------------------------------------------------------------
// Planner — планировщик, часть регулировщика (вариант 11).
//
// Решает одну задачу: выбор следующего процесса из списка готовности для
// выполнения на процессоре. Состояния процессов планировщик не изменяет —
// это делает регулировщик (подпрограмма Process).
//
// Используются относительные динамические приоритеты: текущий активный
// процесс не вытесняется новым поступлением — выбор следующего процесса
// выполняется только при освобождении процессора.
type Planner struct {
	ReadyQueue []*process.PSW // процессы в состоянии «Готов»
}

// ----------------------------------------------------------------------------------------
// Add добавляет процесс в конец очереди готовности.
// Вызывается регулировщиком при переводе процесса в состояние «Готов».
func (p *Planner) Add(psw *process.PSW) {
	p.ReadyQueue = append(p.ReadyQueue, psw)
}

// ----------------------------------------------------------------------------------------
// Remove исключает процесс из очереди готовности.
// Вызывается регулировщиком при изменении состояния процесса.
func (p *Planner) Remove(psw *process.PSW) {
	for i, r := range p.ReadyQueue {
		if r == psw {
			p.ReadyQueue = append(p.ReadyQueue[:i], p.ReadyQueue[i+1:]...)
			return
		}
	}
}

// ----------------------------------------------------------------------------------------
// SelectNext выбирает процесс с наивысшим DynamicPriority, не изменяя
// ни очередь, ни состояния процессов.
func (p *Planner) SelectNext() *process.PSW {
	if len(p.ReadyQueue) == 0 {
		return nil
	}

	// Формула выбора: процесс с максимальным DynamicPriority;
	// при равенстве приоритетов выбирается стоящий раньше в очереди.
	best := 0
	for i, psw := range p.ReadyQueue {
		if psw.DynamicPriority > p.ReadyQueue[best].DynamicPriority {
			best = i
		}
	}
	return p.ReadyQueue[best]
}

// ----------------------------------------------------------------------------------------
// UpdatePriorities пересчитывает приоритеты процессов в очереди готовности.
// Вызывается каждый такт (шаг Б5 алгоритма такта).
//
// Вариант 11: прирост DynamicPriority тем больше, чем больше размер задания
// (PSW.Task.Size) — приоритет больших заданий увеличивается сильнее.
func (p *Planner) UpdatePriorities() {
	for _, psw := range p.ReadyQueue {
		// Прирост за такт ожидания пропорционален размеру задания.
		psw.DynamicPriority += psw.Task.Size
	}
}
