package process

// State — состояние процесса в модели.
//
// Список возможных состояний по лабораторной работе 5:
// «Готов», «Активен», «Инициализация IO», «Блокирован».
// StateNone используется при выгрузке процесса (запись в таблице удаляется).
type State int

// ----------------------------------------------------------------------------------------
const (
	StateNone      State = iota // процесс не порождён / выгружен
	StateReady                  // «Готов»: находится в очереди планировщика
	StateActive                 // «Активен»: выполняется на центральном процессоре
	StateInitIO                 // «Инициализация IO»: инициализируется операция ввода-вывода
	StateBlockedIO              // «Блокирован»: ожидает окончания операции ввода-вывода
	StateSuspended              // «Приостановлен»: оператор остановил процесс
)

// ----------------------------------------------------------------------------------------
// StateName возвращает название состояния для сообщений и индикации.
func StateName(s State) string {
	switch s {
	case StateNone:
		return "Отсутствует"
	case StateReady:
		return "Готов"
	case StateActive:
		return "Активен"
	case StateInitIO:
		return "Инициализация IO"
	case StateBlockedIO:
		return "Блокирован"
	case StateSuspended:
		return "Приостановлен"
	default:
		return "Неизвестно"
	}
}

// ----------------------------------------------------------------------------------------
// PSW (Process Status Word, слово состояния процесса) описывает
// динамический процесс, порождённый заданием.
//
// Все изменения состояния процесса выполняет только регулировщик
// (подпрограмма Process), остальные модули лишь читают эти поля.
// Ход операции ввода-вывода (номер процессора ВВ и счётчик тактов)
// хранится в состоянии процессора ВВ — см. пакет io.
type PSW struct {
	ID              int   // идентификатор процесса
	Task            *Task // ссылка на задание, породившее процесс
	PC              int   // счётчик команд
	State           State // текущее состояние
	DynamicPriority int   // текущий (динамический) приоритет

	// Статистика времени процесса (лабораторная работа 6): заполняется
	// ядром модели каждый такт по текущему состоянию процесса.
	LoadedAt       int // такт модели, в котором процесс загружен
	WaitTicks      int // время ожидания в очереди готовности, тактов
	ExecTicks      int // время выполнения на центральном процессоре, тактов
	IOTicks        int // время в состоянии «Инициализация IO» и «Блокирован», тактов
	SuspendedTicks int // время в состоянии «Приостановлен», тактов

	// Системные затраты процесса (лабораторная работа 7). Это время,
	// которое процесс провёл бы в системе при обслуживании его системных
	// запросов: загрузка, выбор на ЦПр, инициализация ВВ, прерывание ВВ,
	// завершение. В отличие от WaitTicks/ExecTicks/IOTicks, эти поля
	// начисляются не каждый такт, а в моменты системных действий.
	LoadTicks       int // время загрузки задания, тактов
	TermTicks       int // время завершения задания, тактов
	SwitchTicks     int // время переключений «Готов» → «Активен», тактов
	IOInitTicks     int // время логической инициализации ВВ, тактов
	IOIntrTicks     int // время обслуживания прерываний ВВ, тактов
	SystemWaitTicks int // дополнительное ожидание из-за системных действий, тактов

	// Счётчики системных действий процесса — используются для проверки
	// формул T_mono/T_multi и для индикации.
	DispatchCount   int // сколько раз процесс выбирался на ЦПр
	IORequestCount  int // сколько операций ВВ было инициировано
	IOCompleteCount int // сколько прерываний ВВ было обслужено
}
