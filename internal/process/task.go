// Package process содержит сущности процессов и заданий модели.
//
// Пакет хранит только структуры данных без логики: они передаются
// между менеджером памяти, планировщиком, процессором и подсистемой
// ввода-вывода.
package process

// ----------------------------------------------------------------------------------------
// Task описывает программу до её загрузки в память.
type Task struct {
	ID            int // идентификатор задания
	Size          int // объём памяти, необходимый для загрузки
	TotalCommands int // общее число команд в программе
	IOPercent     int // процент команд ввода-вывода среди всех команд
	BasePriority  int // базовый приоритет, заданный при генерации
}

// ----------------------------------------------------------------------------------------
