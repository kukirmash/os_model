// Package os — ядро и координатор модели операционной системы.
//
// Связывает менеджер памяти, планировщик, процессор и подсистему
// ввода-вывода, содержит главный цикл и обработчик директив оператора.
package os

// ----------------------------------------------------------------------------------------
// Config — параметры конфигурации модели.
type Config struct {
	MemorySize         int // общий объём моделируемой памяти
	TickDurationMs     int // длительность одного такта моделирования (скорость работы)
	IOMaxDuration      int // максимальная длительность операции ввода-вывода, тактов
	PrioritySizeFactor int // прирост DynamicPriority за единицу размера задания (вариант 11)
}

