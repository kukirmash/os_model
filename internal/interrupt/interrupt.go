// Package interrupt моделирует сигналы прерывания и их обработку.
//
// Сигнал формируется источником (процессором ввода-вывода) в момент
// окончания операции и помещается в очередь сигналов (Post). Обработку
// сигналов выполняет супервизор прерываний: ядро модели извлекает сигналы
// (ExtractAll) и через регулировщик изменяет состояния процессов.
package interrupt

import "os_model/internal/process"

// ----------------------------------------------------------------------------------------
// Type — тип (источник) прерывания.
type Type int

// ----------------------------------------------------------------------------------------
const (
	IOComplete Type = iota // окончание операции ввода-вывода
	Timer                  // прерывание от таймера (в варианте 11 не используется)
)

// ----------------------------------------------------------------------------------------
// Signal — смоделированный сигнал прерывания.
type Signal struct {
	Type     Type         // тип прерывания
	Time     int          // такт модели, в котором возникло прерывание
	Process  *process.PSW // процесс, которого касается прерывание
	SourceID int          // номер источника (процессора ввода-вывода)
}

// ----------------------------------------------------------------------------------------
// logLimit — сколько последних сигналов хранится для индикации.
const logLimit = 10

// Supervisor — супервизор прерываний: принимает сигналы от источников,
// накапливает их для обработки и ведёт журнал последних прерываний.
type Supervisor struct {
	Pending []Signal // сигналы, ожидающие обработки
	Log     []Signal // журнал последних сигналов (для индикации)
	Handled int      // всего обработано сигналов
}

// ----------------------------------------------------------------------------------------
// Post — источник публикует сигнал прерывания.
func (s *Supervisor) Post(signal Signal) {
	s.Pending = append(s.Pending, signal)
	s.Log = append(s.Log, signal)
	if len(s.Log) > logLimit {
		s.Log = s.Log[len(s.Log)-logLimit:]
	}
}

// ----------------------------------------------------------------------------------------
// ExtractAll извлекает все накопившиеся сигналы для обработки.
func (s *Supervisor) ExtractAll() []Signal {
	pending := s.Pending
	s.Pending = nil
	s.Handled += len(pending)
	return pending
}
